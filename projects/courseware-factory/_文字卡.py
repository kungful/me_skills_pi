def font(sz):
    return ImageFont.truetype(F, sz)


def wrap(d, text, f, maxw):
    """中文按宽度折行"""
    out, cur = [], ""
    for ch in text:
        if ch == "\n":
            out.append(cur)
            cur = ""
            continue
        if d.textlength(cur + ch, font=f) <= maxw:
            cur += ch
        else:
            out.append(cur)
            cur = ch
    if cur:
        out.append(cur)
    return out


def blocks(d, items, maxw, y, gap=26, lh=1.42):
    """items: [(文本, 字号, 颜色, 上留白)]"""
    for txt, sz, col, pad in items:
        f = font(sz)
        y += pad
        for ln in wrap(d, txt, f, maxw):
            d.text((90, y), ln, font=f, fill=col)
            y += int(sz * lh)
        y += gap
    return y


def card(path, kicker, title, sub, lines, idx, total, footer="绘课工坊"):
    cv = Image.new("RGB", (W, H), CREAM)
    d = ImageDraw.Draw(cv)
    if idx == 1:                                   # 封面：满版绿底 + 居中大字
        d.rectangle((0, 0, W, H), fill=GREEN)
        d.rectangle((90, 300, 250, 312), fill=ORANGE)
        d.text((90, 220), kicker, font=font(48), fill=(255, 255, 255))
        y = 400
        for ln in title.split("\n"):
            for w in wrap(d, ln, font(104), W - 180):
                d.text((90, y), w, font=font(104), fill=(255, 255, 255))
                y += 140
        maxw = W - 180
        y += 40
        for t, sz, c, pad in lines:
            f = font(sz)
            y += pad
            for ln in wrap(d, t, f, maxw):
                d.text((90, y), ln, font=f, fill=(240, 240, 240))
                y += int(sz * 1.42)
        d.text((90, H - 96), footer, font=font(34), fill=(255, 255, 255))
        d.text((W - 190, H - 96), "%d / %d" % (idx, total), font=font(34), fill=(255, 255, 255))
        cv.save(path, quality=94)
        return cv.size

    tl = []
    for ln in (title + "\n" + sub).split("\n"):
        if ln:
            tl += wrap(d, ln, font(84), W - 180)
        else:
            tl.append("")
    band = 190 + len(tl) * 100
    d.rectangle((0, 0, W, band), fill=GREEN)
    d.text((90, 58), kicker, font=font(42), fill=(255, 255, 255))
    y = 126
    for ln in tl:
        d.text((90, y), ln, font=font(84), fill=(255, 255, 255))
        y += 100
    d.rectangle((0, band, W, band + 12), fill=ORANGE)

    maxw = W - 180
    lh = 1.42
    h = 0
    for t, sz, c, pad in lines:
        h += pad + len(wrap(d, t, font(sz), maxw)) * int(sz * lh)
    y = band + 12 + max(60, (H - 150 - (band + 12) - h) // 2)
    for t, sz, c, pad in lines:
        f = font(sz)
        y += pad
        for ln in wrap(d, t, f, maxw):
            d.text((90, y), ln, font=f, fill=c)
            y += int(sz * lh)
