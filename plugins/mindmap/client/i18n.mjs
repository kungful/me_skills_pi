export const STRINGS = { "zh-CN": ZH_CN, "zh-TW": ZH_TW, en: EN };

export function pickLang() {
	const lang = String(document.documentElement.lang || navigator.language || "en").toLowerCase();
	if (lang.startsWith("zh-hant") || lang.startsWith("zh-tw") || lang.startsWith("zh-hk")) return "zh-TW";
	if (lang.startsWith("zh")) return "zh-CN";
	return "en";
}

/** 简易插值：`{count}` / `{name}` 占位符。 */
export function format(template, vars) {
	return String(template).replace(/\{(\w+)\}/g, (all, key) => (vars && key in vars ? String(vars[key]) : all));
}

/** 取一套文案 + 模型层要的类型标签。 */
export function getStrings(lang = pickLang()) {
	const S = STRINGS[lang] ?? EN;
	return {
		...S,
		lang,
		kinds: {
			goal: S.kindGoal,
			condition: S.kindCondition,
			step: S.kindStep,
			idea: S.kindIdea,
			risk: S.kindRisk,
			result: S.kindResult,
			image: S.kindImage,
		},
	};
}
