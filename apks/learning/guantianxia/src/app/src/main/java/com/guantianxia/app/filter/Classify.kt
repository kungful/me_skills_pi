 *
 * 起因：中文政治/军事 RSS 已绝迹（新华网停在 2020-12、人民网停在 2025-06、
 * 中国军网 81.cn 只有 http、央视军事页是 JS 渲染）。军事新闻只能从
 * 「时政 / 国际 / 社会」里用关键词捞。
 *
 * 这里只提供词表，判定分两处用：
 *  - 查询期：Db.query(MIL) 拼 LIKE 条件（这样军事新闻既在军事也在国际，
 *    不会因为归类把国际频道掏空）；
 *  - 分析期：Importance 判断重要性。
 */
