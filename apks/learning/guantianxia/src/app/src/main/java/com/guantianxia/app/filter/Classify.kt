    /** 军事关键词。命中即认为这条是军事新闻 */
    val MIL_WORDS = listOf(
        "军演", "演习", "部队", "解放军", "国防", "导弹", "战机", "军舰", "航母",
        "舰艇", "士兵", "军官", "军区", "战区", "阅兵", "空军", "海军", "陆军",
