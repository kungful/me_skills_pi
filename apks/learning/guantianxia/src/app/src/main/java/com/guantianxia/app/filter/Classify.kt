        "旅长", "舰长", "雷达", "反导", "核潜艇", "核武器", "炮弹", "空袭",
        "轰炸", "驻军", "军费", "军火", "停火", "交火", "开火", "军事基地",
        "军援", "军售", "弹道", "巡航", "军机", "护卫舰", "驱逐舰", "潜艇",
        "坦克", "装甲", "炮兵", "伞兵", "特种兵", "维和", "征兵", "退役军人",
        "民兵", "预备役", "国防部", "总参谋部", "军报", "军网", "前线", "战事",
        "战火", "开战", "军备", "防空", "增兵", "军力", "出兵", "撤军",
        "核试验", "舰队", "编队", "战备", "军控", "裁军", "军贸", "兵役",
        "军营", "北约", "俄军", "乌军", "美军", "以军", "革命卫队", "胡塞武装",
        "塔利班", "雇佣兵", "国民警卫队", "自卫队", "哨所", "南海", "台海",
        "反舰", "装甲车", "火炮", "弹药", "击落", "击毙", "阵亡", "武装冲突"
    )

    /** 允许被军事关键词「借走」的频道。科技/财经里的「无人机」之类不算军事 */
    val UPGRADABLE = listOf(Category.CN, Category.POLITICS, Category.INTL, Category.SOCIETY)

    fun isMilitary(text: String): Boolean = MIL_WORDS.any { text.contains(it) }
}
